#!/bin/sh
# embed.sh: turns the files under www/ into C arrays (src/www.h), so the map page is compiled into
# gpstiles and the program stays one file. Usage: tools/embed.sh www/FILE... > build/gen/www.c
set -eu
echo "/* Generated by tools/embed.sh from www/. Do not edit. */"
echo '#include "www.h"'
n=0
for file in "$@"; do
    echo "static const unsigned char file$n[] = {"
    od -An -v -tx1 "$file" | sed -e 's/  */ /g' -e 's/^ //' -e 's/ *$//' -e '/^$/d' -e 's/\([0-9a-f][0-9a-f]\)/0x\1,/g'
    echo "};"
    n=$((n + 1))
done
echo "const struct www_file www_files[] = {"
n=0
for file in "$@"; do
    path=${file#www}
    [ "$path" = /index.html ] && path=/
    case $file in
    *.html) type="text/html; charset=utf-8" ;;
    *.js) type="text/javascript; charset=utf-8" ;;
    *.css) type="text/css; charset=utf-8" ;;
    *) echo "embed.sh: no content type for $file" >&2; exit 1 ;;
    esac
    echo "    {\"$path\", \"$type\", file$n, sizeof file$n},"
    n=$((n + 1))
done
echo "};"
echo "const size_t www_file_count = $n;"
